#!/bin/sh
# sranime-cli config module — validation and management helpers

validate_config() {
    _file="$1"
    _errors=0
    [ ! -f "$_file" ] && return 0

    _line_no=0
    while IFS= read -r _line; do
        _line_no=$((_line_no + 1))
        case "$_line" in
            ''|'#'*) continue ;;
        esac
        case "$_line" in
            *=*)
                _key=$(printf '%s' "$_line" | cut -d= -f1 | tr -d '[:space:]')
                case "$_key" in
                    player|mode|quality|download_dir|menu_program|skip_intro|log_episode|\
                    player_extra_flags|menu_extra_flags|no_detach|exit_after_play|\
                    active_provider|enable_preview)
                        ;;
                    *)
                        printf "  \033[1;33mWarning:\033[0m Line %d: unknown key '%s'\n" "$_line_no" "$_key" >&2
                        ;;
                esac
                ;;
            *)
                printf "  \033[1;31mError:\033[0m Line %d: invalid syntax\n" "$_line_no" >&2
                _errors=$((_errors + 1))
                ;;
        esac
    done <"$_file"

    if grep -q '^mode=' "$_file" 2>/dev/null; then
        _mode=$(grep '^mode=' "$_file" | tail -n1 | cut -d= -f2 | tr -d '"' | tr -d "'")
        case "$_mode" in
            sub|dub) ;;
            *) printf "  \033[1;33mWarning:\033[0m mode should be 'sub' or 'dub', got '%s'\n" "$_mode" >&2 ;;
        esac
    fi
    return "$_errors"
}

generate_default_config() {
    cat << 'CONFIGEOF'
# sranime-cli configuration file
# Generated by sranime-cli --dump-config
# Place this file in ~/.config/sranime-cli/sranime-cli.conf

# Preferred audio mode: sub or dub
mode="sub"

# Default video quality: best, 1080p, 720p, 480p, 360p, worst
quality="best"

# Default download directory
download_dir="$HOME/Downloads"

# Preferred stream provider: hianime, allanime, gogo
active_provider="hianime"

# Preferred video player (e.g. mpv, vlc, iina)
player="mpv"

# Interactive menu program: fzf, rofi, dmenu
menu_program="fzf"

# Enable or disable rich terminal preview pane in fzf (1 or 0)
enable_preview=1

# Automatically skip intros with ani-skip (external tool, mpv only, 1 or 0)
skip_intro=0

# Log watched episodes to system logger (1 or 0)
log_episode=1
CONFIGEOF
}
