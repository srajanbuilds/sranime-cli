#!/bin/sh
# sranime-cli config module — validation and management helpers

validate_config() {
    _file="$1"
    _errors=0
    [ ! -f "$_file" ] && return 0

    _line_no=0
    while IFS= read -r _line; do
        _line_no=$((_line_no + 1))
        case "$_line" in
            ''|'#'*) continue ;;
        esac
        case "$_line" in
            *=*)
                _key=$(printf '%s' "$_line" | cut -d= -f1 | tr -d '[:space:]')
                case "$_key" in
                    player|mode|quality|download_dir|menu_program|skip_intro|log_episode|\
                    player_extra_flags|menu_extra_flags|no_detach|exit_after_play)
                        ;;
                    *)
                        printf "  \033[1;33mWarning:\033[0m Line %d: unknown key '%s'\n" "$_line_no" "$_key" >&2
                        ;;
                esac
                ;;
            *)
                printf "  \033[1;31mError:\033[0m Line %d: invalid syntax\n" "$_line_no" >&2
                _errors=$((_errors + 1))
                ;;
        esac
    done <"$_file"

    if grep -q '^mode=' "$_file" 2>/dev/null; then
        _mode=$(grep '^mode=' "$_file" | tail -n1 | cut -d= -f2 | tr -d '"' | tr -d "'")
        case "$_mode" in
            sub|dub) ;;
            *) printf "  \033[1;33mWarning:\033[0m mode should be 'sub' or 'dub', got '%s'\n" "$_mode" >&2 ;;
        esac
    fi
    return "$_errors"
}

